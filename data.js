/* 根据类别 ID 查找类别 */
function getCategoryById(categoryId) {
  return patternCategories.find(category => category.id === categoryId);
}

/* 根据纹样 ID 查找纹样及其所属类别 */
function getPatternById(patternId) {
  for (const category of patternCategories) {
    const pattern = category.patterns.find(item => item.id === patternId);

    if (pattern) {
      return {
        ...pattern,
        categoryId: category.id,
        categoryName: category.name
      };
    }
  }

  return null;
}
